#[derive(Serialize)]
struct Build<'a> {
    command: &'a str,
}

#[derive(Serialize)]
struct Triggers {
    crons: Vec<String>,
}

// Wrangler envs don't inherit vars or bindings, so every env gets a fully merged copy.
#[derive(Serialize)]
struct Resources {
    // Always written, even empty: wrangler envs inherit triggers, and doko owns the schedule.
    triggers: Triggers,
    vars: Vars,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    kv_namespaces: Vec<Bound<Kv>>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    r2_buckets: Vec<Bound<R2>>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    d1_databases: Vec<Bound<D1>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    queues: Option<Queues>,
    #[serde(skip_serializing_if = "Option::is_none")]
    durable_objects: Option<DurableObjects>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    send_email: Vec<Named<Email>>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    hyperdrive: Vec<Bound<Hyperdrive>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    ai: Option<AiBinding>,
    /// The `[wrangler]` table, minus `vars`.
    #[serde(flatten)]
    extra: Table,
}

#[derive(Serialize)]
struct Bound<T> {
    binding: String,
    #[serde(flatten)]
    inner: T,
}

#[derive(Serialize)]
#[allow(non_snake_case)]
struct Vars {
    DOKO_ENV: String,
    DOKO_CONFIG: Table,
    DOKO_TASKS: BTreeMap<String, String>,
    DOKO_AUTH: Table,
    #[serde(skip_serializing_if = "Table::is_empty")]
    DOKO_MIDDLEWARE: Table,
    // A string: wrangler vars that are numbers don't read back as text.
    #[serde(skip_serializing_if = "Option::is_none")]
    DOKO_REQUEST_TIMEOUT_SECS: Option<String>,
    /// `[wrangler.vars]`, read with `ctx.var(name)`.
    #[serde(flatten)]
    user: Table,
}

pub struct Output {
    pub wrangler_toml: String,
    /// Contents of `src/bindings.rs`, when doko.toml declares any bindings.
    pub bindings_rs: Option<String>,
    /// D1 binding names across all environments, for `doko generate migration`.
    pub d1: Vec<String>,
    /// D1 binding names per environment (including `"dev"`), for `doko migrate`.
    pub d1_by_env: BTreeMap<String, Vec<String>>,
    /// Hyperdrive bindings of the `dev` environment with their local database, for `doko migrate --pg`.
    pub hyperdrive: BTreeMap<String, Option<String>>,
    /// Where each D1 binding's migrations live, relative to the app.
    pub d1_dirs: BTreeMap<String, String>,
    /// `[secrets] required`, plus `SESSION_SECRET` when the app declares a session store.
    pub secrets: Vec<String>,
    /// Hyperdrive bindings without an `id`, per environment: deploying such an env fails.
    pub hyperdrive_without_id: BTreeMap<String, Vec<String>>,
}

pub fn render(doko_toml: &str) -> Result<Output, String> {
    render_over(doko_toml, "")
}

/// Like [`render`], keeping the Durable Object migrations already in `previous_wrangler_toml`:
/// wrangler applies migrations by tag, in order, so history is only ever appended to.
pub fn render_over(doko_toml: &str, previous_wrangler_toml: &str) -> Result<Output, String> {
    let cfg: DokoToml = toml::from_str(doko_toml).map_err(|e| format!("doko.toml: {e}"))?;
    if !is_valid_app_name(&cfg.app.name) {
        return Err(format!(
            "doko.toml: app.name `{}` must be lowercase letters, digits and `-` (cannot end with `-`)",
            cfg.app.name
        ));
    }
    if !is_valid_compatibility_date(&cfg.app.compatibility_date) {
        return Err(format!("doko.toml: app.compatibility_date `{}` must be YYYY-MM-DD", cfg.app.compatibility_date));
    }
    if cfg.app.request_timeout_secs == Some(0) {
        return Err("doko.toml: app.request_timeout_secs must be at least 1".into());
    }
    for name in cfg.env.keys() {
        let valid = !name.is_empty()
            && !name.starts_with('-')
            && !name.ends_with('-')
            && name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
        if !valid {
            return Err(format!(
                "doko.toml: env name `{name}` must be lowercase letters, digits or `-` (cannot start or end with `-`)"
            ));
        }
    }
    let resources_for = |env: &str| -> Result<(Resources, Bindings), String> {
        let mut config = cfg.config.clone();
        let mut b = cfg.bindings.clone();
        let mut tasks = cfg.tasks.clone();
        let mut auth = cfg.auth.clone();
        let mut middleware = cfg.middleware.clone();
        let mut extra = cfg.wrangler.clone();
        if env == DEFAULT_ENV {
            // Workers Logs, unless [wrangler.observability] says otherwise. Envs inherit it.
            extra
                .entry("observability")
                .or_insert_with(|| Value::Table(Table::from_iter([("enabled".to_owned(), Value::Boolean(true))])));
        } else {
            extra.retain(|k, _| !TOP_LEVEL_ONLY.contains(&k));
        }
        if let Some(e) = cfg.env.get(env) {
            merge(&mut extra, &e.wrangler);
            merge(&mut middleware, &e.middleware);
            merge(&mut config, &e.config);
            merge(&mut auth, &e.auth);
            tasks.extend(e.tasks.clone());
            b.queues.extend(e.bindings.queues.clone());
            b.kv.extend(e.bindings.kv.clone());
            b.r2.extend(e.bindings.r2.clone());
            b.d1.extend(e.bindings.d1.clone());
            b.durable.extend(e.bindings.durable.clone());
            b.email.extend(e.bindings.email.clone());
            b.hyperdrive.extend(e.bindings.hyperdrive.clone());
            b.ai = e.bindings.ai.clone().or(b.ai);
        }
        let at = if env == DEFAULT_ENV { String::new() } else { format!(" [env.{env}]") };
        check_binding_names(&b).map_err(|e| format!("doko.toml{at}: {e}"))?;
        check_resources(&b).map_err(|e| format!("doko.toml{at}: {e}"))?;
        check_and_normalize_tasks(&mut tasks).map_err(|e| format!("doko.toml{at}: {e}"))?;
        check_auth(&auth).map_err(|e| format!("doko.toml{at}: {e}"))?;
        check_middleware(&middleware).map_err(|e| format!("doko.toml{at}: {e}"))?;
        let (user_vars, extra) = passthrough(extra).map_err(|e| format!("doko.toml{at}: {e}"))?;
        let mut crons: Vec<String> = tasks.values().cloned().collect();
        crons.sort();
        crons.dedup();
        let queues = (!b.queues.is_empty()).then(|| Queues {
            producers: b.queues.iter().map(|(k, q)| Producer { binding: k.clone(), queue: q.queue.clone() }).collect(),
            consumers: b.queues.values().filter(|q| q.consume).cloned().collect(),
        });
        let durable_objects = (!b.durable.is_empty()).then(|| DurableObjects {
            bindings: b
                .durable
                .iter()
                .map(|(k, d)| DoBinding { name: k.clone(), class_name: d.class_name.clone() })
                .collect(),
        });
        let r = Resources {
            triggers: Triggers { crons },
            vars: Vars {
                DOKO_ENV: env.to_owned(),
                DOKO_CONFIG: config,
                DOKO_TASKS: tasks,
                DOKO_AUTH: auth,
                DOKO_MIDDLEWARE: middleware,
                DOKO_REQUEST_TIMEOUT_SECS: cfg.app.request_timeout_secs.map(|s| s.to_string()),
                user: user_vars,
            },
            kv_namespaces: bound(&b.kv),
            r2_buckets: bound(&b.r2),
            d1_databases: bound(&b.d1),
            queues,
            durable_objects,
            send_email: b.email.iter().map(|(k, e)| Named { name: k.clone(), inner: e.clone() }).collect(),
            hyperdrive: bound(&b.hyperdrive)
                .into_iter()
                .map(|mut h| {
                    h.inner.id.get_or_insert_with(|| HYPERDRIVE_ID_UNSET.to_owned());
                    h
                })
                .collect(),
            ai: b.ai.as_ref().map(|_| AiBinding { binding: AI_BINDING }),
            extra,
        };
        Ok((r, b))
    };

    for name in &cfg.secrets.required {
        let valid = name.starts_with(|c: char| c.is_ascii_uppercase())
            && name.chars().all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_');
        if !valid || name.starts_with("DOKO_") {
            return Err(format!(
                "doko.toml: [secrets] required: `{name}` must be UPPER_SNAKE_CASE and not start with DOKO_"
            ));
        }
    }
    let without_id =
        |b: &Bindings| b.hyperdrive.iter().filter(|(_, h)| h.id.is_none()).map(|(k, _)| k.clone()).collect::<Vec<_>>();
    let (resources, mut all) = resources_for(DEFAULT_ENV)?;
    let mut hyperdrive_without_id = BTreeMap::from([(DEFAULT_ENV.to_owned(), without_id(&all))]);
    // Every class in any env: migrations are shared, and an env override may bind a different class.
    let mut classes: BTreeSet<String> = all.durable.values().map(|d| d.class_name.clone()).collect();
    let hyperdrive = all.hyperdrive.iter().map(|(k, h)| (k.clone(), h.local_connection_string.clone())).collect();
    let mut d1_by_env = BTreeMap::new();
    d1_by_env.insert(DEFAULT_ENV.to_owned(), all.d1.keys().cloned().collect());
    let mut env = BTreeMap::new();
    // `dev` is the top level, not a wrangler env.
    for name in cfg.env.keys().filter(|k| *k != DEFAULT_ENV) {
        let (r, b) = resources_for(name)?;
        d1_by_env.insert(name.clone(), b.d1.keys().cloned().collect());
        hyperdrive_without_id.insert(name.clone(), without_id(&b));
        all.kv.extend(b.kv);
        all.r2.extend(b.r2);
        all.d1.extend(b.d1);
        all.durable.extend(b.durable.clone());
        all.email.extend(b.email);
        all.hyperdrive.extend(b.hyperdrive);
        all.ai = all.ai.or(b.ai);
        all.queues.extend(b.queues);
        classes.extend(b.durable.into_values().map(|d| d.class_name));
        env.insert(name.as_str(), r);
    }
    check_binding_names(&all).map_err(|e| format!("doko.toml: {e}"))?;
    let migrations = migrations(previous_wrangler_toml, &classes, &cfg.app)?;
    let app = &cfg.app;
    let wrangler = Wrangler {
        name: &app.name,
        main: "build/index.js",
        compatibility_date: &app.compatibility_date,
        build: Build { command: BUILD_COMMAND },
        migrations,
        resources,
        env,
    };
    let body = toml::to_string(&wrangler).map_err(|e| e.to_string())?;
    let mut secrets = cfg.secrets.required.clone();
    // doko::auth's sessions and signed tokens can't work without it.
    if (all.kv.contains_key("SESSIONS") || all.durable.contains_key("SESSIONS"))
        && !secrets.iter().any(|s| s == "SESSION_SECRET")
    {
        secrets.push("SESSION_SECRET".into());
    }
    Ok(Output {
        wrangler_toml: format!("# Generated by doko from doko.toml. Do not edit.\n{body}"),
        bindings_rs: bindings_rs(&all),
        d1_dirs: all
            .d1
            .iter()
            .map(|(k, d)| (k.clone(), d.migrations_dir.clone().unwrap_or_else(|| "migrations".into())))
            .collect(),
        d1: all.d1.into_keys().collect(),
        d1_by_env,
        hyperdrive,
        secrets,
        hyperdrive_without_id,
    })
}

#[derive(Deserialize)]
struct Previous {
    #[serde(default)]
    migrations: Vec<Table>,
}

/// The previous migrations, plus one for what doko.toml asks for that hasn't happened yet: the
/// renames and deletions under `[app]`, and the declared classes that don't exist.
fn migrations(previous_wrangler_toml: &str, classes: &BTreeSet<String>, app: &App) -> Result<Vec<Table>, String> {
    let mut migrations = toml::from_str::<Previous>(previous_wrangler_toml)
        .map_err(|e| format!("wrangler.toml: reading existing Durable Object migrations: {e}"))?
        .migrations;
    let names = |m: &Table, key: &str| -> Vec<String> {
        m.get(key)
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(|v| v.as_str().map(str::to_owned))
            .collect()
    };
    let mut live = BTreeSet::new();
    for m in &migrations {
        live.extend(names(m, "new_sqlite_classes"));
        live.extend(names(m, "new_classes"));
        for (from, to) in m
            .get("renamed_classes")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(|r| Some((r.get("from")?.as_str()?.to_owned(), r.get("to")?.as_str()?.to_owned())))
        {
            live.remove(&from);
            live.insert(to);
        }
        for class in names(m, "deleted_classes") {
            live.remove(&class);
        }
    }
    // Both lists are applied once: an entry whose migration is already in the history does nothing,
    // so it can stay in doko.toml.
    let mut renamed = Vec::new();
    for r in &app.renamed_classes {
        if live.contains(&r.from) && !live.contains(&r.to) {
            live.remove(&r.from);
            live.insert(r.to.clone());
            let mut t = Table::new();
            t.insert("from".into(), Value::String(r.from.clone()));
            t.insert("to".into(), Value::String(r.to.clone()));
            renamed.push(Value::Table(t));
        }
    }
    let mut deleted = Vec::new();
    for class in &app.deleted_classes {
        if classes.contains(class) {
            return Err(format!(
                "doko.toml: class `{class}` is in app.deleted_classes but still has a [do.<NAME>] entry"
            ));
        }
        if live.remove(class) {
            deleted.push(Value::String(class.clone()));
        }
    }
    // Deleting a class destroys everything its objects stored, so doko only does it when told to.
    if let Some(gone) = live.difference(classes).next() {
        return Err(format!(
            "doko.toml: Durable Object class `{gone}` has a migration in wrangler.toml but no [do.<NAME>] entry. \
             Restore the entry. Or, under [app], add `renamed_classes = [{{ from = \"{gone}\", to = \"<NewName>\" }}]` \
             if you renamed it, or `deleted_classes = [\"{gone}\"]` to delete the class AND ITS STORED DATA on the next deploy."
        ));
    }
    let new: Vec<Value> = classes.difference(&live).cloned().map(Value::String).collect();
    let mut m = Table::new();
    for (key, values) in [("new_sqlite_classes", new), ("renamed_classes", renamed), ("deleted_classes", deleted)] {
        if !values.is_empty() {
            m.insert(key.into(), Value::Array(values));
        }
    }
    if !m.is_empty() {
        m.insert("tag".into(), Value::String(format!("v{}", migrations.len() + 1)));
        migrations.push(m);
    }
    Ok(migrations)
}

fn bound<T: Clone>(m: &BTreeMap<String, T>) -> Vec<Bound<T>> {
    m.iter().map(|(k, v)| Bound { binding: k.clone(), inner: v.clone() }).collect()
}

fn check_and_normalize_tasks(tasks: &mut BTreeMap<String, String>) -> Result<(), String> {
    for (name, schedule) in tasks.iter_mut() {
        if name.is_empty()
            || !name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_' || c == '-')
        {
            return Err(format!("task `{name}` must be lowercase letters, digits, `_` or `-`"));
        }
        // Workers cron: 5 fields (minute hour day month weekday).
        let fields: Vec<&str> = schedule.split_whitespace().collect();
        if fields.len() != 5 {
            return Err(format!("task `{name}`: schedule `{schedule}` must have 5 fields, e.g. \"0 3 * * *\""));
        }
        *schedule = fields.join(" ");
    }
    Ok(())
}

fn check_resources(b: &Bindings) -> Result<(), String> {
    for (binding, r2) in &b.r2 {
        if r2.bucket_name.trim().is_empty() {
            return Err(format!("r2 `{binding}`: `bucket_name` must not be empty"));
        }
    }
    for (binding, d1) in &b.d1 {
        if d1.database_name.trim().is_empty() {
            return Err(format!("d1 `{binding}`: `database_name` must not be empty"));
        }
    }
    for (binding, d) in &b.durable {
        let c = &d.class_name;
        // The class is a Rust type name passed to `doko::app!`.
        if !c.starts_with(|ch: char| ch.is_ascii_uppercase()) || !c.chars().all(|ch| ch.is_ascii_alphanumeric()) {
            return Err(format!("do `{binding}`: `class_name` must be a Rust type name like `Counter` (got `{c}`)"));
        }
    }
    let mut seen_queues = BTreeSet::new();
    for (binding, q) in &b.queues {
        if q.queue.trim().is_empty() {
            return Err(format!("queue `{binding}`: `queue` must not be empty"));
        }
        if matches!(&q.dead_letter_queue, Some(dlq) if dlq.trim().is_empty()) {
            return Err(format!("queue `{binding}`: `dead_letter_queue` must not be empty"));
        }
        if !seen_queues.insert(&q.queue) {
            return Err(format!("queue `{}` is consumed by multiple bindings", q.queue));
        }
    }
    Ok(())
}

fn check_binding_names(b: &Bindings) -> Result<(), String> {
    let names =
        b.kv.keys()
            .chain(b.r2.keys())
            .chain(b.d1.keys())
            .chain(b.queues.keys())
            .chain(b.durable.keys())
            .chain(b.email.keys());
    let names = names.chain(b.hyperdrive.keys());
    let mut seen = BTreeSet::new();
    // `[ai]` takes this name in every env that declares it.
    let ai = AI_BINDING.to_owned();
    if b.ai.is_some() {
        seen.insert(&ai);
    }
    for name in names {
        let valid = name.starts_with(|c: char| c.is_ascii_uppercase())
            && name.chars().all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_');
        if !valid {
            return Err(format!("binding `{name}` must be UPPER_SNAKE_CASE"));
        }
        if name.starts_with("DOKO_") {
            return Err(format!("binding `{name}`: the DOKO_ prefix is reserved"));
        }
        if !seen.insert(name) {
            return Err(format!("binding `{name}` is declared more than once"));
        }
    }
    Ok(())
}

fn bindings_rs(b: &Bindings) -> Option<String> {
    let none = b.kv.is_empty() && b.r2.is_empty() && b.d1.is_empty() && b.queues.is_empty() && b.durable.is_empty();
    if none && b.email.is_empty() && b.hyperdrive.is_empty() {
        return None;
    }
    let mut s = format!("{BINDINGS_HEADER}\n");
    let kinds: [(&str, Vec<&String>); 7] = [
        ("Kv", b.kv.keys().collect()),
        ("R2", b.r2.keys().collect()),
        ("D1", b.d1.keys().collect()),
        ("Queue", b.queues.keys().collect()),
        ("Do", b.durable.keys().collect()),
        ("Email", b.email.keys().collect()),
        ("Hyperdrive", b.hyperdrive.keys().collect()),
    ];
    for (kind, names) in kinds {
        for name in names {
            let _ = writeln!(s, "pub const {name}: doko::{kind}Binding = doko::{kind}Binding::new(\"{name}\");");
        }
    }
    Some(s)
}

fn merge(base: &mut Table, over: &Table) {
    for (k, v) in over {
        match (base.get_mut(k), v) {
            (Some(Value::Table(b)), Value::Table(o)) => merge(b, o),
            _ => {
                base.insert(k.clone(), v.clone());
            }
        }
    }
}

