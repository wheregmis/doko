pub fn is_valid_app_name(name: &str) -> bool {
    name.starts_with(|c: char| c.is_ascii_lowercase())
        && !name.ends_with('-')
        && name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
}

fn is_valid_compatibility_date(date: &str) -> bool {
    let b = date.as_bytes();
    if b.len() != 10 || b[4] != b'-' || b[7] != b'-' {
        return false;
    }
    if !b.iter().enumerate().all(|(i, c)| i == 4 || i == 7 || c.is_ascii_digit()) {
        return false;
    }
    let month: u8 = date[5..7].parse().unwrap_or(0);
    let day: u8 = date[8..10].parse().unwrap_or(0);
    (1..=12).contains(&month) && (1..=31).contains(&day)
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct DokoToml {
    app: App,
    /// App config, read at runtime with `ctx.config::<T>()`.
    #[serde(default)]
    config: Table,
    /// Cron tasks: `name = "schedule"`. Handlers are registered in `Hooks::tasks`.
    #[serde(default)]
    tasks: BTreeMap<String, String>,
    /// Settings for `doko::auth`: see [`Auth`].
    #[serde(default)]
    auth: Table,
    /// What doko puts around every request: see [`Middleware`].
    #[serde(default)]
    middleware: Table,
    /// Wrangler settings doko has no table for, copied into wrangler.toml as written.
    #[serde(default)]
    wrangler: Table,
    #[serde(default)]
    secrets: Secrets,
    #[serde(flatten)]
    bindings: Bindings,
    #[serde(default)]
    env: BTreeMap<String, Env>,
}

