//! `doko`: generates `wrangler.toml` from `doko.toml`, drives wrangler, and scaffolds code.

mod config;
mod generate;

use std::{
    fs,
    path::Path,
    process::{Command, ExitCode},
};

const USAGE: &str = "\
usage:
  doko new <app>                      scaffold a new app in ./<app>
  doko config                         regenerate wrangler.toml (and src/bindings.rs) from doko.toml
  doko dev [wrangler args]            regenerate, then `wrangler dev`
  doko deploy [wrangler args]         regenerate, then `wrangler deploy` (e.g. --env prod)
  doko migrate [wrangler args]        apply D1 migrations to every D1 binding (local unless --remote)
  doko generate controller <name>     scaffold src/controllers/<name>.rs (alias: g)
  doko generate job <name>            scaffold src/jobs/<name>.rs
  doko generate migration <name> [DB] new D1 migration file (DB needed with several D1 bindings)";
const WRANGLER: &str = "wrangler@4";
const BINDINGS_RS: &str = "src/bindings.rs";

/// Regenerates wrangler.toml and src/bindings.rs, returning the rendered config output.
fn write_config() -> Result<config::Output, String> {
    let src = fs::read_to_string("doko.toml").map_err(|e| format!("reading doko.toml: {e}"))?;
    // The existing wrangler.toml holds the Durable Object migration history, so commit it.
    let out = config::render_over(&src, &fs::read_to_string("wrangler.toml").unwrap_or_default())?;
    write_if_changed("wrangler.toml", &out.wrangler_toml)?;
    if let Some(rs) = &out.bindings_rs {
        // Skip unchanged writes so cargo doesn't rebuild for nothing.
        write_if_changed(BINDINGS_RS, rs)?;
    } else if fs::read_to_string(BINDINGS_RS).is_ok_and(|s| s.starts_with("//! Generated by doko")) {
        write_if_changed(BINDINGS_RS, config::BINDINGS_HEADER)?;
    }
    Ok(out)
}

fn write_if_changed(path: &str, content: &str) -> Result<(), String> {
    if fs::read_to_string(path).ok().as_deref() != Some(content) {
        fs::write(path, content).map_err(|e| format!("writing {path}: {e}"))?;
    }
    Ok(())
}

fn migrate_env<'a>(args: &[&'a str]) -> Result<&'a str, String> {
    let mut iter = args.iter().copied();
    let mut env = "dev";
    while let Some(arg) = iter.next() {
        if arg == "--env" || arg == "-e" {
            env = iter.next().ok_or_else(|| format!("missing value for `{arg}`"))?;
        } else if let Some(val) = arg.strip_prefix("--env=").or_else(|| arg.strip_prefix("-e=")) {
            if val.is_empty() {
                return Err("missing value for `--env=`".into());
            }
            env = val;
        }
    }
    Ok(env)
}

fn wrangler<S: AsRef<std::ffi::OsStr>>(args: &[S]) -> Result<(), String> {
    let status = Command::new("npx")
        .args(["--yes", WRANGLER])
        .args(args)
        .status()
        .map_err(|e| format!("running npx {WRANGLER}: {e}"))?;
    if status.success() { Ok(()) } else { Err(format!("wrangler exited with {status}")) }
}

fn run(args: &[String]) -> Result<(), String> {
    let strs: Vec<&str> = args.iter().map(String::as_str).collect();
    match strs.as_slice() {
        ["-h" | "--help"] => {
            println!("{USAGE}");
            Ok(())
        }
        ["-V" | "--version"] => {
            println!("doko {}", env!("CARGO_PKG_VERSION"));
            Ok(())
        }
        ["config"] => {
            write_config()?;
            println!("wrote wrangler.toml");
            Ok(())
        }
        ["dev" | "deploy", ..] => {
            write_config()?;
            wrangler(args)
        }
        ["migrate", rest @ ..] => {
            let out = write_config()?;
            let env = migrate_env(rest)?;
            let dbs = out
                .d1_by_env
                .get(env)
                .ok_or_else(|| format!("env `{env}` is not defined in doko.toml"))?;
            if dbs.is_empty() {
                return Err(format!("doko.toml declares no [d1.<BINDING>] databases for env `{env}`"));
            }
            for db in dbs {
                wrangler(&[&["d1", "migrations", "apply", db.as_str()], rest].concat())?;
            }
            Ok(())
        }
        ["generate" | "g", "controller", name] => {
            for path in generate::controller(Path::new("."), name)? {
                println!("wrote {path}");
            }
            println!("make sure your app has `mod controllers;` and merges `controllers::routes()` in Hooks::routes");
            Ok(())
        }
        ["new", name] => {
            generate::app(Path::new("."), name)?;
            println!("created {name}/. Next: cd {name} && doko dev");
            Ok(())
        }
        ["generate" | "g", "job", name] => {
            for path in generate::job(Path::new("."), name)? {
                println!("wrote {path}");
            }
            println!("make sure your app has `mod jobs;`, returns `jobs::jobs()` from Hooks::jobs, and has a [queues.<NAME>] in doko.toml");
            Ok(())
        }
        ["generate" | "g", "migration", name, db @ ..] => {
            let dbs = write_config()?.d1;
            let db = match (db, dbs.as_slice()) {
                ([db], _) if dbs.iter().any(|d| d == db) => *db,
                ([db], _) => return Err(format!("`{db}` is not a [d1.<BINDING>] in doko.toml")),
                ([], [only]) => only.as_str(),
                ([], []) => return Err("doko.toml declares no [d1.<BINDING>] databases".into()),
                _ => return Err(format!("several D1 bindings; name one: doko g migration {name} <{}>", dbs.join("|"))),
            };
            wrangler(&["d1", "migrations", "create", db, name])
        }
        _ => Err(USAGE.to_owned()),
    }
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match run(&args) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("{e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_migrate_env() {
        assert_eq!(migrate_env(&[]).unwrap(), "dev");
        assert_eq!(migrate_env(&["--remote"]).unwrap(), "dev");
        assert_eq!(migrate_env(&["--remote", "--env", "prod"]).unwrap(), "prod");
        assert_eq!(migrate_env(&["--env=staging"]).unwrap(), "staging");
        assert_eq!(migrate_env(&["-e", "preview"]).unwrap(), "preview");
        assert_eq!(migrate_env(&["-e=qa"]).unwrap(), "qa");
        assert!(migrate_env(&["--env"]).is_err());
        assert!(migrate_env(&["--env="]).is_err());
    }
}
